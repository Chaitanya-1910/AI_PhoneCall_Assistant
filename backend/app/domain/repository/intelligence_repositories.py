from typing import Protocol, List, Optional
from app.domain.conversation.memory import LongTermMemory
from app.domain.intelligence.models import ConversationSummary, StructuredAction

class ConversationRepository(Protocol):
    async def save_memory(self, memory: LongTermMemory) -> None: ...
    async def get_memory(self, session_id: str) -> Optional[LongTermMemory]: ...

class SummaryRepository(Protocol):
    async def save_summary(self, summary: ConversationSummary) -> None: ...
    async def get_summary(self, session_id: str) -> Optional[ConversationSummary]: ...

class TaskRepository(Protocol):
    async def create_task(self, action: StructuredAction) -> None: ...
    async def list_tasks(self, session_id: str) -> List[StructuredAction]: ...

class ReminderRepository(Protocol):
    async def create_reminder(self, action: StructuredAction) -> None: ...
